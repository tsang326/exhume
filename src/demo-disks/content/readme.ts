/** Converts an ASCII string to bytes. Throws on a character outside 0x00 to 0x7F. */
export function asciiBytes(text: string): Uint8Array {
  const out = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const c = text.charCodeAt(i);
    if (c > 0x7f) throw new RangeError('text is not ASCII');
    out[i] = c;
  }
  return out;
}
